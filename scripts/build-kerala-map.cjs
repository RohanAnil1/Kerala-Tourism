// Rebuild the display geometry from the checked-in, attributed geographic data.
// The website build never depends on a mapping API or a network request.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const feature = JSON.parse(fs.readFileSync(path.join(root, 'public/maps/kerala.geojson'), 'utf8'));
if (feature.properties.shapeISO !== 'IN-KL') throw new Error('Expected the Kerala boundary');
const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
const points = polygons.flat(2);
const west = Math.min(...points.map(point => point[0]));
const east = Math.max(...points.map(point => point[0]));
const south = Math.min(...points.map(point => point[1]));
const north = Math.max(...points.map(point => point[1]));
const longitudeScale = Math.cos(((south + north) / 2) * Math.PI / 180);
const scale = Math.min(350 / ((east - west) * longitudeScale), 680 / (north - south));
const offsetX = (520 - (east - west) * longitudeScale * scale) / 2;
const offsetY = 45;
const project = ([longitude, latitude]) => [offsetX + (longitude - west) * longitudeScale * scale, offsetY + (north - latitude) * scale];
const outline = polygons.map(polygon => polygon.map(ring => ring.map((point, index) => `${index ? 'L' : 'M'}${project(point).map(value => value.toFixed(2)).join(',')}`).join('') + 'Z').join('')).join('');
const source = `// Generated by scripts/build-kerala-map.cjs from public/maps/kerala.geojson.
// geoBoundaries / DataMeet India community / Election Commission of India.
// CC BY 2.5 IN; source, license and adaptations are credited on /credits#kerala-map.
export const KERALA_MAP_VIEWBOX = '0 0 520 780';
export const KERALA_BOUNDARY_PATH = ${JSON.stringify(outline)};
export const KERALA_MAP_BOUNDS = ${JSON.stringify({ west, south, east, north })};

/** Equirectangular projection, corrected for longitude scale at Kerala's mid-latitude. */
export function projectKeralaPoint({ lat, lng }: { lat: number; lng: number }) {
  return {
    x: ${offsetX} + (lng - ${west}) * ${longitudeScale} * ${scale},
    y: ${offsetY} + (${north} - lat) * ${scale},
  };
}
`;
fs.writeFileSync(path.join(root, 'src/data/kerala-map.ts'), source);
console.log(`Generated Kerala outline: ${points.length} geographic vertices; ${outline.length} SVG characters.`);
